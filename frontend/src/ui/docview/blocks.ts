export const blockRange = (name: string): [number, number] | null => {
  const n = name.toLowerCase().replace(/_/g, ' ');
  const hit = BLOCKS.find((b) => b[0].toLowerCase() === n);
  return hit ? [hit[1], hit[2]] : null;
};
